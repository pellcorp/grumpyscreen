"""Moonraker's file manager over a per-session copy of the test prints.

At startup the library (tools/sim_gcodes) is copied into
<session>/gcodes, so deleting, moving or uploading only ever touches this
session's copy. Metadata comes out of the files themselves with moonraker's
PrusaSlicer-path parsers (metadata.py), and the embedded thumbnails are
written to .thumbs/ the way moonraker extracts them.
"""
import asyncio
import base64
import json
import os
import re
import shutil
import time
import uuid

from . import state as S
from .state import RpcError, STATE, notify

GCODE_EXT = (".gcode", ".g", ".gco", ".ufp", ".nc")
METADATA = {}           # relative path -> metadata dict


def root():
    return os.path.join(S.ARGS.session_dir, "gcodes")


def setup():
    """A fresh session copy of the library."""
    if os.path.isdir(root()):
        shutil.rmtree(root())
    shutil.copytree(S.ARGS.gcodes, root())
    METADATA.clear()
    now = time.time()
    for i, rel in enumerate(walk()):
        # a few hours apart, so a newest-first list has an order to show
        os.utime(os.path.join(root(), rel), (now - i * 9000, now - i * 9000))
        scan(rel)


def walk():
    out = []
    for d, dirs, files in os.walk(root()):
        dirs[:] = [x for x in dirs if not x.startswith(".")]
        for f in files:
            if f.lower().endswith(GCODE_EXT):
                out.append(os.path.relpath(os.path.join(d, f), root()).replace(os.sep, "/"))
    return sorted(out, key=str.lower)


# ------------------------------------------------------------------ metadata
F = r"([0-9]*\.?[0-9]+)"


def find(pattern, text, cast=float):
    m = re.search(pattern, text)
    if not m:
        return None
    try:
        return cast(m.group(1))
    except ValueError:
        return None


def str_list(pattern, text):
    m = re.search(pattern, text)
    if not m:
        return None
    items = [x.strip().strip('"') for x in re.findall(r'"[^"]*"|[^;,]+', m.group(1)) if x.strip()]
    return items


def scan(rel):
    """metadata.py's PrusaSlicer parser path, as OrcaSlicer files go through it."""
    path = os.path.join(root(), rel)
    st = os.stat(path)
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        data = f.read()
    header, footer = data[:1 << 20], data[-(1 << 20):]
    meta = {"size": st.st_size, "modified": round(st.st_mtime, 3),
            "uuid": str(uuid.uuid5(uuid.NAMESPACE_URL, S.ARGS.session_dir + rel)),
            "file_processors": []}
    m = re.search(r"; generated by (.+?) on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}", header)
    if m:
        name, _, version = m.group(1).rpartition(" ")
        meta.update(slicer=name, slicer_version=version)
    else:
        meta["slicer"] = "Unknown"
    m = re.search(r"\n[MG]\d+\s.*\n", header)
    if m:
        meta["gcode_start_byte"] = len(header[:m.start()].encode())
    rev = footer[::-1]
    m = re.search(r"\n.*\s\d+[MG]\n", rev)
    if m:
        meta["gcode_end_byte"] = st.st_size - len(rev[:m.start()].encode())
    v = find(r"; total layers count = ([0-9]+)", footer, int)
    if v is not None:
        meta["layer_count"] = v
    heights = [float(z) for z in re.findall(r";BEFORE_LAYER_CHANGE\n(?:.*\n)?;(\d+\.?\d*)", footer)]
    if heights:
        meta["object_height"] = max(heights)
    m = re.search(r";\sestimated\sprinting\stime.*", footer)
    if m:
        total = 0
        for unit, mult in (("d", 86400), ("h", 3600), ("m", 60), ("s", 1)):
            u = re.search(r"(\d+)" + unit, m.group(0).split("=")[-1])
            if u:
                total += int(u.group(1)) * mult
        meta["estimated_time"] = total
    for key, pat in (("nozzle_diameter", r";\snozzle_diameter\s=\s" + F),
                     ("layer_height", r"; layer_height = " + F)):
        v = find(pat, footer)
        if v is not None:
            meta[key] = v
    pct = find(r"; first_layer_height = " + F + "%", footer)
    if pct is not None and "layer_height" in meta:
        meta["first_layer_height"] = round(pct / 100 * meta["layer_height"], 6)
    else:
        v = find(r"; first_layer_height = " + F, footer)
        if v is not None:
            meta["first_layer_height"] = v
    for key, pat in (("first_layer_extr_temp", r"; first_layer_temperature = " + F),
                     ("first_layer_bed_temp", r"; first_layer_bed_temperature = " + F),
                     ("chamber_temp", r"; chamber_temperature = " + F)):
        v = find(pat, footer)
        if v is not None:
            meta[key] = v
    for key, pat in (("filament_name", r";\sfilament_settings_id\s=\s(.*)"),
                     ("filament_type", r";\sfilament_type\s=\s(.*)")):
        items = str_list(pat, footer)
        if items:
            meta[key] = json.dumps(items) if len(items) > 1 else items[0]
    meta["filament_colors"] = str_list(r";\sfilament_colour\s=\s(.*)", footer) or []
    v = find(r"; total toolchanges = ([0-9]+)", footer, int)
    if v is None:
        v = find(r"; total filament change = ([0-9]+)", footer, int)
    if v is not None:
        meta["filament_change_count"] = v
    meta["extruder_colors"] = str_list(r";\sextruder_colour\s=\s(.*)", footer) or []
    temps = str_list(r";\s(?:nozzle_)?temperature\s=\s(.*)", footer)
    if temps:
        try:
            meta["filament_temps"] = [int(t) for t in temps]
        except ValueError:
            pass
    tools = str_list(r";\sreferenced_tools\s=\s(.*)", footer)
    meta["referenced_tools"] = [int(t) for t in tools] if tools else []
    v = find(r";\ssingle_extruder_multi_material\s=\s([0-9]+)", footer, int)
    if v is not None:
        meta["mmu_print"] = v
    m = re.search(r"filament\sused\s\[mm\]\s=\s(.*)\n", footer)
    if m:
        meta["filament_total"] = round(sum(float(x) for x in re.findall(F, m.group(1))), 2)
    v = find(r"total\sfilament\sused\s\[g\]\s=\s" + F, footer)
    if v is not None:
        meta["filament_weight_total"] = v
    m = re.search(r"filament\sused\s\[g\]\s=\s(.*)\n", footer)
    if m:
        meta["filament_weights"] = [float(x) for x in re.findall(F, m.group(1))]
    for key in ("printer_vendor", "printer_model", "printer_variant"):
        m = re.search(r"; %s = (.*)" % key, footer)
        if m:
            meta[key] = m.group(1).strip().strip('"')
    thumbs = extract_thumbnails(rel, data if len(data) <= 2 << 20 else header + footer)
    if thumbs:
        meta["thumbnails"] = thumbs
    meta.update(print_start_time=None, job_id=None)
    METADATA[rel] = meta


def extract_thumbnails(rel, text):
    out = []
    d = os.path.dirname(os.path.join(root(), rel))
    stem = os.path.splitext(os.path.basename(rel))[0]
    for m in re.finditer(r"(thumbnail(?:_[A-Za-z0-9]+)?) begin([;/\+=\w\s]+?); \1 end", text):
        lines = m.group(2).split("\n")
        head = re.fullmatch(r"\s*(\d+)x(\d+) (\d+)\s*", lines[0])
        if not head:
            continue
        w, h, size = (int(x) for x in head.groups())
        b64 = "".join(l.strip().lstrip(";").strip() for l in lines[1:])
        if len(b64) != size:
            continue                      # moonraker: "Thumbnail Size Mismatch"
        ext = m.group(1).partition("_")[2].lower() or "png"
        if ext not in ("png", "jpg"):
            continue
        rel_thumb = ".thumbs/%s-%dx%d.%s" % (stem, w, h, ext)
        os.makedirs(os.path.join(d, ".thumbs"), exist_ok=True)
        raw = base64.b64decode(b64)
        with open(os.path.join(d, rel_thumb), "wb") as f:
            f.write(raw)
        out.append({"width": w, "height": h, "size": len(raw), "relative_path": rel_thumb})
    return out


def metadata(filename):
    meta = METADATA.get(filename)
    if meta is None:
        raise RpcError("Metadata not available for <%s>" % filename, -32601)
    return dict(meta, filename=filename)


# ------------------------------------------------------------------ requests
def split(path):
    path = path.strip("/")
    r, _, rest = path.partition("/")
    if r != "gcodes":
        raise RpcError("Invalid root path (%s)" % r)
    full = os.path.normpath(os.path.join(root(), rest))
    if not full.startswith(os.path.normpath(root())):
        raise RpcError("Invalid path request, '%s'' is outside root '%s'" % (path, r))
    return rest, full


def item(rel, full, deleted=False):
    if deleted:
        return {"path": rel, "root": "gcodes", "modified": 0, "size": 0, "permissions": ""}
    st = os.stat(full)
    return {"path": rel, "root": "gcodes", "modified": round(st.st_mtime, 3),
            "size": st.st_size, "permissions": "rw"}


def in_use(rel):
    ps = STATE.get("print_stats", {})
    return (S.KLIPPY["state"] == "ready" and ps.get("state") in ("printing", "paused")
            and (ps.get("filename") == rel or ps.get("filename", "").startswith(rel.rstrip("/") + "/")))


async def changed(action, it, source=None):
    payload = {"action": action, "item": it}
    if source:
        payload["source_item"] = source
    await asyncio.sleep(0.25)
    await notify("notify_filelist_changed", payload)


def file_list(root_name="gcodes"):
    if root_name != "gcodes":
        if root_name in ("config", "logs"):
            return []
        raise RpcError("Failed to build file list, invalid path: %s: None" % root_name)
    return [{k: v for k, v in item(rel, os.path.join(root(), rel)).items() if k != "root"} for rel in walk()]


def roots():
    return [{"name": "gcodes", "path": root(), "permissions": "rw"},
            {"name": "config", "path": os.path.join(S.ARGS.session_dir, "config"), "permissions": "rw"},
            {"name": "logs", "path": os.path.join(S.ARGS.session_dir, "logs"), "permissions": "r"}]


def get_directory(path="gcodes", extended=False):
    rel, full = split(path)
    if not os.path.isdir(full):
        raise RpcError("Directory does not exist (%s)" % full)
    dirs, files = [], []
    for name in sorted(os.listdir(full), key=str.lower):
        p = os.path.join(full, name)
        st = os.stat(p)
        if os.path.isdir(p):
            dirs.append({"modified": round(st.st_mtime, 3), "size": 4096, "permissions": "rw", "dirname": name})
        else:
            f = {"modified": round(st.st_mtime, 3), "size": st.st_size, "permissions": "rw", "filename": name}
            key = (rel + "/" + name).strip("/")
            if extended and key in METADATA:
                f.update({k: v for k, v in METADATA[key].items()})
            files.append(f)
    du = shutil.disk_usage(root())
    return {"dirs": dirs, "files": files,
            "disk_usage": {"total": du.total, "used": du.used, "free": du.free},
            "root_info": {"name": "gcodes", "permissions": "rw"}}


async def delete_file(path):
    rel, full = split(path)
    if not os.path.isfile(full):
        raise RpcError("Invalid file path: %s" % path)
    if in_use(rel):
        raise RpcError("File currently in use", 403)
    os.remove(full)
    for t in METADATA.pop(rel, {}).get("thumbnails", []):
        p = os.path.join(os.path.dirname(full), t["relative_path"])
        if os.path.exists(p):
            os.remove(p)
    it = item(rel, full, deleted=True)
    asyncio.create_task(changed("delete_file", it))
    return {"item": it, "action": "delete_file"}


async def post_directory(path):
    rel, full = split(path)
    try:
        os.mkdir(full)
    except OSError as e:
        raise RpcError(str(e))
    it = item(rel, full)
    asyncio.create_task(changed("create_dir", it))
    return {"item": it, "action": "create_dir"}


async def delete_directory(path, force=False):
    rel, full = split(path)
    if not rel:
        raise RpcError("Cannot delete root directory")
    if not os.path.isdir(full):
        raise RpcError("Directory does not exist (%s)" % path)
    if force and in_use(rel + "/"):
        raise RpcError("File currently in use", 403)
    try:
        if force:
            shutil.rmtree(full)
        else:
            os.rmdir(full)
    except OSError as e:
        raise RpcError(str(e))
    for k in [k for k in METADATA if k.startswith(rel + "/")]:
        METADATA.pop(k)
    it = item(rel, full, deleted=True)
    asyncio.create_task(changed("delete_dir", it))
    return {"item": it, "action": "delete_dir"}


async def move_copy(source, dest, copy):
    srel, sfull = split(source)
    drel, dfull = split(dest)
    if not os.path.exists(sfull):
        raise RpcError("File %s does not exist" % sfull)
    if os.path.exists(dfull) and in_use(drel):
        raise RpcError("File currently in use", 403)
    if not copy and in_use(srel):
        raise RpcError("File currently in use", 403)
    is_dir = os.path.isdir(sfull)
    existed = os.path.exists(dfull)
    try:
        final = (shutil.copytree(sfull, dfull) if is_dir else shutil.copy2(sfull, dfull)) if copy \
            else shutil.move(sfull, dfull)
    except OSError as e:
        raise RpcError(str(e))
    frel = os.path.relpath(final, root()).replace(os.sep, "/")
    if not copy:
        for k in [k for k in METADATA if k == srel or k.startswith(srel + "/")]:
            METADATA.pop(k)
    for rel in walk():
        if rel not in METADATA:
            scan(rel)
    it = item(frel, final)
    if copy:
        action = ("create_dir" if is_dir else "modify_file" if existed else "create_file")
        asyncio.create_task(changed(action, it))
        return {"item": it, "action": action}
    action = "move_dir" if is_dir else "move_file"
    src = {"path": srel, "root": "gcodes"}
    asyncio.create_task(changed(action, it, src))
    return {"item": it, "source_item": src, "action": action}


async def add_file(rel, data):
    """A new file arriving, as an upload does: written, scanned, announced."""
    full = os.path.join(root(), rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "wb") as f:
        f.write(data)
    scan(rel)
    asyncio.create_task(changed("create_file", item(rel, full)))
