#!/usr/bin/env python3
"""Generate the optional Happy Hare fallback from DejaVuSansMono.ttf.

Usage: python3 tools/make_console_font.py /path/to/DejaVuSansMono.ttf
Requires Node/npm; uses lv_font_conv 1.5.3. --converter accepts a local JS copy.
The source font and licence are documented in docs/simulator.md.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile


# HH mmu_constants.py: punctuation, box drawing, blocks, arrows and sensors.
# Latin, Greek, NBSP and superscripts already live in the main console font.
SYMBOLS = "—•─━│┈┌┐└┘├┤┫┬┴┼═█▌■▶▷▼◀◁◉●◯"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--converter", type=Path)
    args = parser.parse_args()
    converter = (["node", str(args.converter)] if args.converter
                 else ["npx", "--yes", "lv_font_conv@1.5.3"])
    with tempfile.TemporaryDirectory(prefix="grumpy-console-font-") as directory:
        output = Path(directory) / "font.c"
        subprocess.run(converter + [
            "--font", str(args.font), "--size", "14", "--bpp", "4", "--format", "lvgl",
            "--no-compress", "--no-kerning", "--symbols", SYMBOLS,
            "--lv-font-name", "dejavusans_mono_hh_14", "-o", str(output),
        ], check=True)
        generated = output.read_text(encoding="utf-8")
    # Keep generated metadata independent of local source/output paths.
    generated = generated[generated.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
    # Match the primary font's line metrics for consistent fallback use.
    generated = generated.replace(".line_height = 18,", ".line_height = 20,")
    generated = generated.replace(".base_line = 4,", ".base_line = 5,")
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    header = ("/* Generated by tools/make_console_font.py using lv_font_conv 1.5.3.\n"
              " * DejaVu Sans Mono, 14px, 4bpp; see LICENSE-DejaVu.txt.\n"
              " * Source font SHA256: " + digest + "\n */\n"
              "#ifndef COSMOS\n")
    destination = Path(__file__).resolve().parent.parent / "assets/dejavusans_mono_hh_14.c"
    destination.write_text(header + generated + "\n#endif /* !COSMOS */\n", encoding="utf-8")


if __name__ == "__main__":
    main()
