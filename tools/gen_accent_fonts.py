#!/usr/bin/env python3
"""Generates assets/lang_accents_<size>.c: the accented Latin letters LVGL's
built-in Montserrat leaves out. Needs Pillow. Usage: gen_accent_fonts.py <ttf>"""
import pathlib
import sys

from PIL import ImageFont

SIZES = (12, 14, 16, 18, 20, 22, 24, 26, 28)
# Western European, Romanian (Ă ă, Ș ș Ț ț), then Czech (Č č Ď ď, Ě ě, Ň ň, Ř ř Š š, Ť ť, Ů ů, Ž ž)
RANGES = ((0xC0, 0xFF), (0x102, 0x103), (0x10C, 0x10F), (0x11A, 0x11B), (0x147, 0x148),
          (0x158, 0x161), (0x164, 0x165), (0x16E, 0x16F), (0x17D, 0x17E), (0x218, 0x21B))
ASSETS = pathlib.Path(__file__).resolve().parent.parent / "assets"
BIG_SIZE = 24  # the small-screen build leaves this size and up out of flash


def glyph_bytes(mask, width, height):
    nibbles = [mask.getpixel((x, y)) >> 4 for y in range(height) for x in range(width)]
    if len(nibbles) % 2:
        nibbles.append(0)
    return [nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2)]


def generate(ttf, size):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    bitmap = []
    glyphs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
    for code in (c for first, last in RANGES for c in range(first, last + 1)):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        mask = font.getmask(char, mode="L")
        assert mask.size == (width, height), (char, size, mask.size, width, height)
        glyphs.append(
            f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {round(font.getlength(char) * 16)}, "
            f".box_w = {width}, .box_h = {height}, .ofs_x = {left}, .ofs_y = {-bottom}}}")
        bitmap += glyph_bytes(mask, width, height)

    rows = [", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]
    name = f"lang_accents_{size}"
    ranges = ", ".join(f"U+{first:04X}-U+{last:04X}" for first, last in RANGES)
    cmaps, glyph_id = [], 1
    for first, last in RANGES:
        cmaps.append(
            f"    {{.range_start = {first}, .range_length = {last - first + 1}, .glyph_id_start = {glyph_id},\n"
            "     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,\n"
            "     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}")
        glyph_id += last - first + 1
    guard = "LV_FONT_MONTSERRAT_24" if size >= BIG_SIZE else "1"
    return f"""// Generated by tools/gen_accent_fonts.py from Montserrat-Medium.ttf, {ranges}
#include "lvgl/lvgl.h"

#if {guard}

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {(",\n    ").join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(",\n").join(glyphs)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
{(",\n").join(cmaps)}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(RANGES)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .dsc = &font_dsc,
}};

#endif
"""


def main():
    for size in SIZES:
        path = ASSETS / f"lang_accents_{size}.c"
        path.write_text(generate(sys.argv[1], size), encoding="utf-8", newline="\n")
        print(path.name, path.stat().st_size)


if __name__ == "__main__":
    main()
