#!/usr/bin/env python3
"""Generate both bitmap sizes for the shared navigation SVGs.

    python3 tools/make_nav_icons.py

Requires rsvg-convert and ImageMagick. The white SVG masks live in
assets/material_svg/nav_*.svg. The Material Design icons are extracted from
assets/materialdesignicons-webfont.ttf; Spoolman uses its own logo.
The generated LVGL true-colour images support zooming, unlike alpha-only images.
"""
from pathlib import Path
import shutil
import subprocess


ROOT = Path(__file__).resolve().parent.parent


def bitmap(svg, size):
    png = subprocess.check_output([
        "rsvg-convert", str(svg), "-w", str(size), "-h", str(size),
    ])
    rgba = subprocess.run([
        shutil.which("magick") or "convert", "png:-", "-depth", "8", "rgba:-",
    ], input=png, stdout=subprocess.PIPE, check=True).stdout
    if len(rgba) != size * size * 4:
        raise ValueError(f"Unexpected bitmap size for {svg}")
    if any(rgba[i + 3] and rgba[i:i + 3] != b"\xff\xff\xff"
           for i in range(0, len(rgba), 4)):
        raise ValueError(f"Expected a white icon mask: {svg}")
    return rgba[3::4]


def image_source(name, size, alpha):
    out = [
        "/* Generated by tools/make_nav_icons.py; do not edit. */",
        '#include "lvgl/lvgl.h"',
        "",
        f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{",
    ]
    for condition, color_bytes in [
        ("LV_COLOR_DEPTH == 1 || LV_COLOR_DEPTH == 8", 1),
        ("LV_COLOR_DEPTH == 16", 2),
        ("LV_COLOR_DEPTH == 32", 3),
    ]:
        out.append(f"#if {condition}")
        # White is all bits set at every colour depth, including swapped RGB565.
        pixels = b"".join(b"\xff" * color_bytes + bytes([a]) for a in alpha)
        for start in range(0, len(pixels), 64):
            out.append("  " + ", ".join(f"0x{v:02x}" for v in pixels[start:start + 64]) + ",")
        out.append("#endif")
    out.extend([
        "};", "",
        f"const lv_img_dsc_t {name} = {{",
        "  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,",
        "  .header.always_zero = 0,",
        "  .header.reserved = 0,",
        f"  .header.w = {size},",
        f"  .header.h = {size},",
        f"  .data_size = sizeof({name}_map),",
        f"  .data = {name}_map,",
        "};", "",
    ])
    return "\n".join(out)


def main():
    for svg in sorted((ROOT / "assets/material_svg").glob("nav_*.svg")):
        for directory, size in [("material", 64), ("material_46", 46)]:
            output = ROOT / "assets" / directory / f"{svg.stem}.c"
            output.write_text(image_source(svg.stem, size, bitmap(svg, size)))
            print(output.relative_to(ROOT))


if __name__ == "__main__":
    main()
