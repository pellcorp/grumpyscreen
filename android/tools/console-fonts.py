#!/usr/bin/env python3
"""Generate the Android console's monospace fonts from DejaVuSansMono.ttf.

The printer builds draw the console log in assets/dejavusans_mono_14.c, the
one font that does not scale: fine at 800x480, tiny on a phone. The app picks
one of these instead, at the size the rest of the UI's text has grown to (the
same steps as Theme::scale_font). They hold ASCII, Latin-1 and Happy Hare's
symbols; anything else falls back to the 14px font, which has the rest.

Usage: python3 android/tools/console-fonts.py [/path/to/DejaVuSansMono.ttf]
Requires Node/npm; uses lv_font_conv 1.5.3 (as tools/make_console_font.py).
"""
import argparse
import hashlib
import subprocess
import tempfile
from pathlib import Path

SIZES = [16, 18, 20, 22, 24, 26, 28]
# ASCII, Latin-1 (degree sign, NBSP, ...) and Happy Hare's mmu_constants.py
# symbols, as in tools/make_console_font.py
RANGES = "0x20-0x7E,0xA0-0xFF"
SYMBOLS = "—•─━│┈┌┐└┘├┤┫┬┴┼═█▌■▶▷▼◀◁◉●◯"

OUT = Path(__file__).resolve().parent.parent / "app/src/main/cpp/fonts"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, nargs="?",
                        default=Path("/usr/share/fonts/TTF/DejaVuSansMono.ttf"))
    args = parser.parse_args()
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    OUT.mkdir(parents=True, exist_ok=True)
    for size in SIZES:
        name = "console_mono_%d" % size
        with tempfile.TemporaryDirectory(prefix="grumpy-console-font-") as d:
            out = Path(d) / "font.c"
            subprocess.run(["npx", "--yes", "lv_font_conv@1.5.3",
                            "--font", str(args.font), "--size", str(size), "--bpp", "4",
                            "--format", "lvgl", "--no-compress", "--no-kerning",
                            "-r", RANGES, "--symbols", SYMBOLS,
                            "--lv-font-name", name, "-o", str(out)], check=True)
            c = out.read_text(encoding="utf-8")
        # no local paths in the output
        c = c[c.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
        # the rest of the 14px font's glyphs (Greek, Cyrillic, ...)
        assert c.count(".fallback = NULL,") == 1, name
        c = c.replace(".fallback = NULL,", ".fallback = &dejavusans_mono_14,")
        c = c.replace("#if " + name.upper(), "LV_FONT_DECLARE(dejavusans_mono_14);\n\n#if " + name.upper(), 1)
        header = ("/* Generated by android/tools/console-fonts.py using lv_font_conv 1.5.3.\n"
                  " * DejaVu Sans Mono, %dpx, 4bpp; licence in docs/simulator.md.\n"
                  " * Source font SHA256: %s\n */\n" % (size, digest))
        (OUT / (name + ".c")).write_text(header + c, encoding="utf-8")
        print("wrote", OUT / (name + ".c"))


if __name__ == "__main__":
    main()
